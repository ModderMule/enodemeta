// ServerSearch: how one eD2K server searches and browses the file catalogue of
// another.
//
// MetaIngest runs server → daemon and MetaApi runs client → server; this
// service runs server → server. A server that implements it answers for the
// files its own connected users share, and for nothing else: not the rows it
// took from a catalogue daemon, and not the rows it learned from another
// server. That is what keeps a file from travelling round a ring of servers.
//
// # No client is ever identified
//
// A user chose the server they logged into, not the servers it talks to. So no
// message here carries an address, a port, a client id or a user hash, and no
// call returns a source. A row says a file exists and how many users of the
// answering server share it; finding a source stays between the client and the
// networks it already uses. A field that could identify a client must never be
// added to this file.
//
// # Discovery
//
// A server learns of another either from its own configuration or from the
// ST_SERVER_SEARCH tag of the UDP server description reply, and asks
// GetServerInfo what is offered before it calls anything else.

